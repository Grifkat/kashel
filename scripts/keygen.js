// Ключи для подписи обновлений. Запуск: npm run keygen
//
// Делается один раз. Закрытый ключ кладётся ВНЕ проекта, в домашний каталог:
// в репозитории ему не место — попади он в архив или на диск приятеля, и
// подписать поддельное обновление сможет кто угодно. Открытый ключ пишется
// в electron/updatekey.js и уезжает внутрь программы: ей нужно только
// проверять подпись, а не ставить её.
//
// Второй запуск ключи НЕ перезаписывает: новая пара сделала бы уже
// разданные копии программы неспособными принять обновление. Для замены
// ключа надо сначала удалить старый файл — осознанно и руками.

const crypto = require('node:crypto')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')

const ROOT = path.join(__dirname, '..')
const ЗАКРЫТЫЙ = path.join(os.homedir(), '.kashel-release-key.pem')
const ОТКРЫТЫЙ = path.join(ROOT, 'electron', 'updatekey.js')

const адресъ = process.argv[2]

if (fs.existsSync(ЗАКРЫТЫЙ)) {
  console.log(`Закрытый ключ уже есть: ${ЗАКРЫТЫЙ}`)
  if (адресъ) {
    переписать(прочитатьОткрытый(), адресъ)
    console.log(`Адрес обновлений записан: ${адресъ}`)
  } else {
    console.log('Чтобы поменять адрес обновлений: npm run keygen -- https://ваш-сайт/обновления')
    console.log('Чтобы завести НОВУЮ пару ключей, сначала удалите файл выше вручную.')
    console.log('Осторожно: после смены ключа уже разданные копии программы обновиться не смогут.')
  }
  process.exit(0)
}

const { privateKey, publicKey } = crypto.generateKeyPairSync('ed25519')

fs.writeFileSync(ЗАКРЫТЫЙ, privateKey.export({ format: 'pem', type: 'pkcs8' }), { mode: 0o600 })
const откр = publicKey.export({ format: 'der', type: 'spki' }).toString('base64')
переписать(откр, адресъ || прочитатьАдресъ())

console.log('Пара ключей заведена.')
console.log(`  закрытый (никому не показывать): ${ЗАКРЫТЫЙ}`)
console.log(`  открытый (внутри программы):     ${ОТКРЫТЫЙ}`)
console.log('')
console.log('Сохраните закрытый ключ в надёжном месте. Потеряете — выпускать')
console.log('обновления для уже разданных копий будет нечем.')

function прочитатьОткрытый() {
  try {
    return require(ОТКРЫТЫЙ).ОТКРЫТЫЙ_КЛЮЧЪ
  } catch {
    return ''
  }
}

function прочитатьАдресъ() {
  try {
    return require(ОТКРЫТЫЙ).АДРЕСЪ_ПО_УМОЛЧАНІЮ
  } catch {
    return ''
  }
}

function переписать(ключ, адр) {
  const текстъ = `// Создаётся и переписывается скриптом: npm run keygen
//
// Здесь два значения, и оба нужны программе на чужой машине: чем проверять
// подпись объявления об обновлении и куда за этим объявлением ходить.
// Закрытого ключа тут нет и быть не может — он остаётся у вас.

/** Открытый ключ Ed25519 в виде SPKI, base64. */
const ОТКРЫТЫЙ_КЛЮЧЪ = ${JSON.stringify(ключ || '')}

/** Каталог на вашем хостинге, где лежат update.json и установщики. */
const АДРЕСЪ_ПО_УМОЛЧАНІЮ = ${JSON.stringify(адр || 'https://example.invalid/kashel')}

module.exports = { ОТКРЫТЫЙ_КЛЮЧЪ, АДРЕСЪ_ПО_УМОЛЧАНІЮ }
`
  fs.writeFileSync(ОТКРЫТЫЙ, текстъ, 'utf8')
}
