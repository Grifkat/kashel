/*
 * Сквозная проверка облака на настоящем сервере.
 *
 * Проверяется не «работает ли запись», а то, ради чего всё затевалось: без
 * приглашения места в базе нет, и вошедший человѣкъ не видит чужого. Первое
 * можно прочесть в schema.sql и поверить на слово; второе видно только так.
 */
import { вывестиКлючи, зашифровать, расшифровать, ярлыкъПути } from '../src/lib/crypto'
import {
  всеСтроки, войти, завести, занятьПриглашеніе, записатьСтроку, обновить, однаСтрока,
  удалитьСтроку, выйти, сеансъСвѣжъ, type Сеансъ,
} from '../src/state/supabase'
import { облачноеХранилище } from '../src/state/cloud'

const провалы: string[] = []
const check = (что: string, усл: boolean, доп = '') => {
  console.log(`${усл ? '✓' : '✗'} ${что}${доп ? ' — ' + доп : ''}`)
  if (!усл) провалы.push(что)
}
const отказъ = async (что: string, дѣло: () => Promise<unknown>, ждём?: RegExp) => {
  let вышло = ''
  try { await дѣло(); check(что, false, 'прошло, а не должно было'); return }
  catch (e) { вышло = (e as Error).message }
  check(что, ждём ? ждём.test(вышло) : true, вышло.slice(0, 90))
}

const метка = Date.now().toString(36)
const почтаА = `proba+a${метка}@kashel-proba.ru`
const почтаБ = `proba+b${метка}@kashel-proba.ru`
const КОДЪ_А = 'P89J8-56N9P'
const М = 2000 // обороты занижены: проверяется устройство, не цена перебора

async function главное() {
  console.log(`\n— облако вживую (${метка}) —`)

  // ---- А заводится и занимает приглашение
  const клА = await вывестиКлючи('пароль-А-очень-длинный', почтаА, М)
  const сА0 = await завести(почтаА, клА.пароль)
  check('запись А заведена и сеанс выдан сразу', !!сА0, сА0 ? 'подтверждение почты выключено' : 'нужно подтверждение почты')
  if (!сА0) { console.log('  дальше без подтверждённой почты нельзя'); return }
  let сА: Сеансъ = сА0
  check('сеанс свѣжъ', сеансъСвѣжъ(сА))

  // ---- Без приглашения писать нельзя. Это и есть закрытый круг.
  const ярлыкъА = await ярлыкъПути(клА.пути, 'data.json')
  await отказъ('без приглашения запись не проходит',
    () => записатьСтроку(сА, ярлыкъА, 'ЧТО-УГОДНО', 1), /приглашен|security/i)

  check('чужой код не занимается', (await занятьПриглашеніе(сА, 'НЕТ-ТАКОГО')) === false)
  check('свой код занимается', (await занятьПриглашеніе(сА, КОДЪ_А)) === true)
  check('повторное занятие не ломается', (await занятьПриглашеніе(сА, КОДЪ_А)) === true)

  // ---- Теперь запись проходит, и содержимое возвращается целым
  const тайнаА = 'Счётъ «Комиксъ» · 386 000 ₽ · это видно только А'
  await записатьСтроку(сА, ярлыкъА, await зашифровать(клА.содержимое, тайнаА), 1)
  const строкаА = await однаСтрока(сА, ярлыкъА)
  check('строка записалась', !!строкаА, строкаА ? `версія ${строкаА.version}` : '')
  check('и расшифровывается своим ключом',
    строкаА ? (await расшифровать(клА.содержимое, строкаА.blob)) === тайнаА : false)
  check('на сервере лежит не открытый текст', !строкаА?.blob.includes('Комиксъ'))

  // ---- Б заводится без приглашения
  const клБ = await вывестиКлючи('пароль-Б-совсем-другой', почтаБ, М)
  const сБ0 = await завести(почтаБ, клБ.пароль)
  check('запись Б заведена', !!сБ0)
  if (!сБ0) return
  const сБ: Сеансъ = сБ0

  /*
   * Главное. Б вошёл по-настоящему: у него есть свой токен, и запрос идёт
   * тем же путём, что у А. Увидеть он не должен ничего.
   */
  const уБ = await всеСтроки(сБ)
  check('Б не видит ни одной строки А', уБ.length === 0, `видно строк: ${уБ.length}`)
  const прямо = await однаСтрока(сБ, ярлыкъА)
  check('и по прямому ярлыку тоже не видит', прямо === null)

  const ярлыкъБ = await ярлыкъПути(клБ.пути, 'data.json')
  await отказъ('Б не может писать без приглашения',
    () => записатьСтроку(сБ, ярлыкъБ, 'нахрапом', 1), /приглашен|security/i)

  // Б пробует затереть строку А, подставив её ярлык. Не должен смочь.
  await удалитьСтроку(сБ, ярлыкъА)
  const послѣ = await однаСтрока(сА, ярлыкъА)
  check('Б не смог удалить строку А', !!послѣ)

  // ---- А видит своё после повторного входа
  const сА2 = await войти(почтаА, клА.пароль)
  const своё = await всеСтроки(сА2)
  check('А по-прежнему видит ровно свою строку', своё.length === 1, `строк: ${своё.length}`)

  // ---- Обновление сеанса
  const сА3 = await обновить(сА2)
  check('сеанс обновляется', !!сА3.токенъ && сА3.токенъ !== '', 'токен получен')
  check('и обновлённым сеансом всё ещё видно своё', (await всеСтроки(сА3)).length === 1)

  // ---- Неверный пароль
  await отказъ('с чужим паролем не пускает',
    () => войти(почтаА, 'совершенно-не-тот-пароль'), /не подходит/i)

  /*
   * Хранилище целиком: чтение, запись, список и опись.
   *
   * Проверяется главное свойство описи — что имена файлов возвращаются
   * человѣку, хотя сервер их не знает и знать не может.
   */
  const хрА = облачноеХранилище(сА3, клА)
  await хрА.write('data.json', '{"счета":1}')
  await хрА.write('notes/Долги перед братом.md', '# тайна')
  await хрА.write('notes/Прочее.md', 'мелочь')
  await хрА.write('transactions/2026-09.json', '[]')

  check('прочитано то же, что записано', (await хрА.read('data.json')) === '{"счета":1}')
  check('и с кириллицей в имени',
    (await хрА.read('notes/Долги перед братом.md')) === '# тайна')
  check('несуществующее даёт пустоту', (await хрА.read('нет/такого.json')) === null)

  const заметки = await хрА.list('notes', '.md')
  check('список заметок восстановлен из описи',
    заметки.join('|') === 'Долги перед братом.md|Прочее.md', заметки.join('|'))
  check('список не лезет вглубь', (await хрА.list('')).join('|') === 'data.json', (await хрА.list('')).join('|'))

  // Сервер видит ярлыки и комья — и ничего больше.
  const сырое = JSON.stringify(await всеСтроки(сА3))
  check('на сервере нет имён файлов',
    !сырое.includes('notes') && !сырое.includes('Долги') && !сырое.includes('data.json'))
  check('и нет содержимого', !сырое.includes('тайна') && !сырое.includes('счета'))

  // Переоткрытие: новый сеанс, те же ключи — всё на месте.
  const сА4 = await войти(почтаА, клА.пароль)
  const хрА2 = облачноеХранилище(сА4, клА)
  check('после нового входа опись читается',
    (await хрА2.list('notes', '.md')).length === 2)
  check('и содержимое тоже', (await хрА2.read('notes/Прочее.md')) === 'мелочь')

  // Другой пароль — отказ, а не пустое хранилище.
  const клЧужой = await вывестиКлючи('совсем-другой-пароль', почтаА, М)
  const хрЧужой = облачноеХранилище(сА4, клЧужой)
  check('чужим паролем опись не открывается — и это видно',
    (await хрЧужой.list('notes', '.md')).length === 0)

  await хрА2.remove('notes/Прочее.md')
  check('удалённое пропадает из списка', (await хрА2.list('notes', '.md')).join('|') === 'Долги перед братом.md')
  check('и не читается', (await хрА2.read('notes/Прочее.md')) === null)

  // ---- Уборка за собой
  for (const р of await всеСтроки(сА4)) await удалитьСтроку(сА4, р.path_id)
  check('за собой убрано', (await всеСтроки(сА4)).length === 0)
  await выйти(сА4)
  await выйти(сБ)
}

void главное()
  .catch((e) => { check('проверка не упала целиком', false, (e as Error).message) })
  .finally(() => {
    console.log(`\nПровалено: ${провалы.length}`)
    process.exit(провалы.length ? 1 : 0)
  })
