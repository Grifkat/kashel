/*
 * Шифрование на устройстве.
 *
 * Смысл всей затеи: сервер хранит ком байтов, который сам прочесть не может.
 * Ключ выводится из пароля прямо в браузере и наружу не уходит никогда — ни
 * при входе, ни при сохранении. Отсюда два следствия, и оба надо понимать
 * заранее. Взлом сервера не выдаёт ничьих денег. И забытый пароль означает
 * потерянные данные: восстанавливать нечем, у нас нет ключа.
 *
 * Как устроено. Из пароля один раз добывается общий корень — PBKDF2, дорогой
 * нарочно, чтобы перебор пароля по украденной базе стоил дорого. Из корня
 * расходятся три ключа, и каждый занят своим:
 *
 *   пароль    — его и только его видит сервер. Это не пароль человѣка, а
 *               производная от него: обратить нельзя, а значит из того, что
 *               лежит на сервере, ключа к данным не добыть.
 *   содержимое — им шифруются сами файлы.
 *   пути      — им имена файлов превращаются в неразличимые ярлыки. Иначе
 *               сервер читал бы заголовки заметок прямо из имён.
 *
 * Разводятся они через HKDF, а не тремя прогонами PBKDF2: вход тогда стоил бы
 * человѣку втрое дороже, ничего не прибавляя к стойкости.
 *
 * Ничего своего тут не изобретено и не написано: всё берёт WebCrypto, тот же,
 * что в браузере и в Node. Своя криптография — верный способ получить
 * уверенность вместо защиты.
 */

/** Столько раз прокручивается пароль. Меньше — дешевле перебор по базе. */
export const ОБОРОТОВЪ = 600_000

const цифры = new TextEncoder()
const буквы = new TextDecoder()

const подсистема = (): SubtleCrypto => {
  const c = globalThis.crypto
  if (!c?.subtle) throw new Error('в этом окружении нет WebCrypto — шифровать нечем')
  return c.subtle
}

export interface Ключи {
  /** То, что уходит на сервер вместо пароля. */
  пароль: string
  /** Им шифруется содержимое файлов. */
  содержимое: CryptoKey
  /** Им имена файлов превращаются в ярлыки. */
  пути: CryptoKey
}

/**
 * Три ключа из пароля и почты.
 *
 * Почта входит в соль: одинаковый пароль у двух человѣкъ даёт разные ключи,
 * и общая радужная таблица по базе не строится.
 */
export async function вывестиКлючи(
  пароль: string,
  почта: string,
  оборотовъ: number = ОБОРОТОВЪ,
): Promise<Ключи> {
  const s = подсистема()
  if (!пароль) throw new Error('пустой пароль')
  if (!почта) throw new Error('пустая почта')

  const основа = await s.importKey('raw', цифры.encode(пароль), 'PBKDF2', false, ['deriveBits'])
  const корень = await s.deriveBits(
    {
      name: 'PBKDF2',
      hash: 'SHA-256',
      salt: цифры.encode('Кошель|' + почта.trim().toLowerCase()),
      iterations: оборотовъ,
    },
    основа,
    256,
  )

  const развод = await s.importKey('raw', корень, 'HKDF', false, ['deriveBits'])
  const вѣтвь = async (назначеніе: string) =>
    s.deriveBits(
      { name: 'HKDF', hash: 'SHA-256', salt: new Uint8Array(0), info: цифры.encode(назначеніе) },
      развод,
      256,
    )

  const [дляПароля, дляСодержимаго, дляПутей] = await Promise.all([
    вѣтвь('kashel:auth'),
    вѣтвь('kashel:content'),
    вѣтвь('kashel:path'),
  ])

  return {
    пароль: вБазу64(new Uint8Array(дляПароля)),
    содержимое: await s.importKey('raw', дляСодержимаго, 'AES-GCM', false, ['encrypt', 'decrypt']),
    пути: await s.importKey('raw', дляПутей, { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']),
  }
}

/**
 * Зашифровать строку. Вектор случаен каждый раз и кладётся в начало.
 *
 * Свой вектор на каждую запись обязателен: повтори его при том же ключе, и
 * AES-GCM перестаёт защищать вовсе — по двум записям вскрывается обе.
 */
export async function зашифровать(ключ: CryptoKey, текстъ: string): Promise<string> {
  const s = подсистема()
  const векторъ = globalThis.crypto.getRandomValues(new Uint8Array(12))
  const комъ = await s.encrypt({ name: 'AES-GCM', iv: векторъ }, ключ, цифры.encode(текстъ))
  const всё = new Uint8Array(векторъ.length + комъ.byteLength)
  всё.set(векторъ, 0)
  всё.set(new Uint8Array(комъ), векторъ.length)
  return вБазу64(всё)
}

/**
 * Расшифровать. Чужой ключ или испорченный ком — отказ, а не мусор:
 * за это отвечает встроенная в AES-GCM проверка целости.
 */
export async function расшифровать(ключ: CryptoKey, ком64: string): Promise<string> {
  const s = подсистема()
  const всё = изБазы64(ком64)
  if (всё.length <= 12) throw new Error('запись повреждена')
  try {
    const открытое = await s.decrypt(
      { name: 'AES-GCM', iv: всё.subarray(0, 12) },
      ключ,
      всё.subarray(12),
    )
    return буквы.decode(открытое)
  } catch {
    throw new Error('не расшифровывается: другой пароль или запись повреждена')
  }
}

/**
 * Ярлык пути: имя файла, по которому сервер ничего не узнает.
 *
 * Одинаковый путь даёт одинаковый ярлык — иначе не найти запись при следующем
 * входе. Значит сервер видит, что какой-то файл менялся, но не какой именно:
 * «notes/Долги перед братом.md» и «data.json» для него одинаково бессмысленны.
 */
export async function ярлыкъПути(ключ: CryptoKey, путь: string): Promise<string> {
  const s = подсистема()
  const подпись = await s.sign('HMAC', ключ, цифры.encode(путь))
  return [...new Uint8Array(подпись)].map((b) => b.toString(16).padStart(2, '0')).join('')
}

/**
 * Простой отпечаток строки. Ни от какого ключа не зависит.
 *
 * Нужен там, где имя записи обязано быть одинаковым при любом пароле, —
 * см. провѣрку пароля в state/cloud. Тайны в нём нет и быть не должно.
 */
export async function отпечатокъ(текстъ: string): Promise<string> {
  const s = подсистема()
  const х = await s.digest('SHA-256', цифры.encode(текстъ))
  return [...new Uint8Array(х)].map((b) => b.toString(16).padStart(2, '0')).join('')
}

// ------------------------------------------------------------ основанія 64
// Своими руками, а не btoa: тот работает только с байтами до 256 и на кириллице
// падает, а Buffer есть лишь в Node. Нужно одно и то же в браузере и в проверках.

const АЗБУКА = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'

export function вБазу64(байты: Uint8Array): string {
  let итогъ = ''
  for (let i = 0; i < байты.length; i += 3) {
    const a = байты[i]
    const b = байты[i + 1]
    const c = байты[i + 2]
    итогъ += АЗБУКА[a >> 2]
    итогъ += АЗБУКА[((a & 3) << 4) | ((b ?? 0) >> 4)]
    итогъ += b === undefined ? '=' : АЗБУКА[((b & 15) << 2) | ((c ?? 0) >> 6)]
    итогъ += c === undefined ? '=' : АЗБУКА[c & 63]
  }
  return итогъ
}

// Возвращается ровно нужная длина отдѣльнымъ буферомъ, а не окно въ чужой:
// WebCrypto принимаетъ только видъ надъ обычнымъ ArrayBuffer, и вырѣзка изъ
// общаго буфера ему не годится.
export function изБазы64(текстъ: string): Uint8Array<ArrayBuffer> {
  const чистое = текстъ.replace(/[^A-Za-z0-9+/]/g, '')
  const итогъ = new Uint8Array((чистое.length * 3) >> 2)
  let n = 0
  for (let i = 0; i < чистое.length; i += 4) {
    const a = АЗБУКА.indexOf(чистое[i])
    const b = АЗБУКА.indexOf(чистое[i + 1])
    const c = АЗБУКА.indexOf(чистое[i + 2])
    const d = АЗБУКА.indexOf(чистое[i + 3])
    итогъ[n++] = (a << 2) | (b >> 4)
    if (c >= 0) итогъ[n++] = ((b & 15) << 4) | (c >> 2)
    if (d >= 0) итогъ[n++] = ((c & 3) << 6) | d
  }
  return итогъ.slice(0, n)
}
