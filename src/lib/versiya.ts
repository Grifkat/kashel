export const выпускВерсии = (версия: string): Выпуск | undefined => ВЫПУСКИ.find((в) => в.версия === версия)

/** Сравнение версий вида 1.2.3: отрицательное — a старше b. */
export function сравнитьВерсии(a: string, b: string): number {
  const ч = (s: string) => s.split('.').map((x) => parseInt(x, 10) || 0)
  const [x, y] = [ч(a), ч(b)]
  for (let i = 0; i < Math.max(x.length, y.length); i++) {
    const d = (x[i] ?? 0) - (y[i] ?? 0)
    if (d) return d
  }
  return 0
}

/**
 * Выпуски, которых человек ещё не видел: новее последней виденной версии
 * и не новее нынешней. Хранилище без отметки — это обновление с 1.0.0,
 * если в нём уже что-то есть; у нового хранилища показывать нечего.
 */
export function непросмотренныеВыпуски(видел: string | undefined, естьДанные: boolean, нынешняя = ВЕРСИЯ): Выпуск[] {
  if (!видел && !естьДанные) return []
  const с = видел ?? '1.0.0'
  return ВЫПУСКИ.filter((в) => сравнитьВерсии(в.версия, с) > 0 && сравнитьВерсии(в.версия, нынешняя) <= 0)
}
