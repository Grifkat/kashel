export const themeById = (id: ThemeId): ThemeInfo => THEMES.find((t) => t.id === id) ?? THEMES[0]

/** Ближайшая тема противоположной светлоты — для быстрого переключателя в ленте. */
/** Ближайшая тема противоположной светлоты — для быстрого переключателя в ленте. */
export function counterpart(id: ThemeId): ThemeId {
  const cur = themeById(id)
  const pairs: Record<ThemeId, ThemeId> = {
    obsidian: 'mint',
    mint: 'obsidian',
    graphite: 'warm',
    warm: 'graphite',
    // У имперской свѣтлой пары нѣтъ: тёплая — ближайшая по духу бумага.
    imperial: 'warm',
    glass: 'mint',
    neon: 'warm',
    pickme: 'pickmenoch',
    pickmenoch: 'pickme',
    // Каждая новая тема сделана парой — дневной и ночной, — поэтому
    // переключатель светлоты водит внутри пары, а не в чужую тему.
    znamya: 'znamyaden',
    znamyaden: 'znamya',
    trikolor: 'trikolornoch',
    trikolornoch: 'trikolor',
  }
  return pairs[cur.id]
}
