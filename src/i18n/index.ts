/*
 * Перевод интерфейса: русский и английский.
 *
 * Устроен как gettext: ключ — сама русская строка. Код поэтому читается
 * по-русски как и прежде, а пропущенный перевод показывает русский текст, а
 * не пустоту и не имя ключа.
 *
 * Язык ставится один раз — до загрузки программы (см. main.tsx), а смена
 * языка перезапускает окно. Благодаря этому т() работает где угодно, в том
 * числе в константах модулей, которые вычисляются при загрузке: к этому
 * моменту язык уже известен. Живое переключение без перезапуска потребовало
 * бы протащить язык через каждую константу — ради одного нажатия в настройках.
 *
 * Своих библиотек здесь нет: программа не тянет зависимостей времени
 * выполнения, а весь перевод умещается в сотню строк.
 */
import React from 'react'
import { EN } from './en'

export type Язык = 'ru' | 'en'

let язык: Язык = 'ru'

/** Где зеркало языка лежит в localStorage — его читают до загрузки хранилища. */
export const ГДѢ_ЯЗЫКЪ = 'kashel:язык'

export const поставитьЯзык = (я: Язык) => { язык = я }
export const текущійЯзык = (): Язык => язык

/** Язык из зеркала — для запуска, пока хранилище ещё не прочитано. */
export function языкИзъЗеркала(): Язык {
  try {
    return localStorage.getItem(ГДѢ_ЯЗЫКЪ) === 'en' ? 'en' : 'ru'
  } catch {
    return 'ru'
  }
}

export function запомнитьЯзык(я: Язык) {
  try { localStorage.setItem(ГДѢ_ЯЗЫКЪ, я) } catch { /* приватное окно */ }
}

const перевести = (ключъ: string): string => (язык === 'en' ? EN[ключъ] || ключъ : ключъ)

/** Подстановка {0}, {1}… — в переводе порядок мест может быть любым. */
function подставить(шаблонъ: string, args: unknown[]): string {
  return шаблонъ.replace(/\{(\d+)\}/g, (всё, n) => {
    const i = Number(n)
    return i < args.length ? String(args[i] ?? '') : всё
  })
}

/**
 * Строка на текущем языке. Ключ — русский текст с местами {0}, {1}…
 * В русском режиме возвращает ровно исходную строку: тесты это стерегут.
 */
export function т(ключъ: string, ...args: unknown[]): string {
  const шаблонъ = перевести(ключъ)
  return args.length ? подставить(шаблонъ, args) : шаблонъ
}

/**
 * То же, но места могут быть элементами: <b>…</b>, суммы, значки.
 * Возвращает фрагмент, в котором текст и элементы чередуются.
 */
export function тр(ключъ: string, ...args: React.ReactNode[]): React.ReactElement {
  const шаблонъ = перевести(ключъ)
  const части: React.ReactNode[] = []
  let послѣдній = 0
  for (const м of шаблонъ.matchAll(/\{(\d+)\}/g)) {
    const i = Number(м[1])
    if (м.index! > послѣдній) части.push(шаблонъ.slice(послѣдній, м.index))
    части.push(i < args.length ? args[i] : м[0])
    послѣдній = м.index! + м[0].length
  }
  if (послѣдній < шаблонъ.length) части.push(шаблонъ.slice(послѣдній))
  return React.createElement(React.Fragment, null, ...части)
}

/**
 * Отметка ключа без перевода — для данных, которые переводятся при показе:
 * т(запись.имя). Сама ничего не делает, но сторож видит в ней ключ.
 */
export const тк = (ключъ: string): string => ключъ

