import настройки from '../cloud.json'

/*
 * Настройки облака и одно решение, которое из них следует.
 *
 * Пока ключ не вписан, облака нет: ни входа, ни синхронизации, ни намёка на
 * них в окне. Это не заглушка на время разработки, а нужное поведение —
 * программа обязана работать без всякого сервера, как работала до сих пор,
 * и человѣкъ, скачавший её себе на диск, не должен видеть предложений
 * куда-то войти.
 *
 * Ключ anon публичный по замыслу: он уезжает в страницу к каждому посетителю
 * и сам по себе не даёт ничего. Всё, что можно с ним сделать, ограничено
 * правилами доступа в самой базе — они и есть настоящая защита.
 */

export interface Облако {
  url: string
  anonKey: string
}

const чисто = (s: unknown): string => (typeof s === 'string' ? s.trim() : '')

export const облако: Облако = {
  url: чисто((настройки as Record<string, unknown>).url).replace(/\/+$/, ''),
  anonKey: чисто((настройки as Record<string, unknown>).anonKey),
}

/**
 * Облако настроено и им можно пользоваться.
 *
 * Проверяются оба значения, а не одно: с адресом без ключа программа молча
 * ходила бы в никуда, а ключ без адреса некуда приложить.
 */
export const облакоЕсть = (о: Облако = облако): boolean =>
  /^https:\/\/[^\s/]+$/.test(о.url) && о.anonKey.length > 20

/** Куда стучаться. Без настроенного облака — бросок, а не тихий промах. */
export function адресОблака(путь: string, о: Облако = облако): string {
  if (!облакоЕсть(о)) throw new Error('облако не настроено')
  return о.url + (путь.startsWith('/') ? путь : '/' + путь)
}
