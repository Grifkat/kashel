import type { Account, Money, Transaction, VaultData } from '../lib/types'
import { accountBalance } from './stats'

/*
 * Проектные счета: деньги, которые лежат у вас, но не ваши.
 *
 * Аванс за работу, сбор на издание, бюджет кампании — всё это приходит на
 * ваш счёт и оттуда же расходуется, но своим доходом это не является. Пока
 * приложение считало такие приходы наравне с гонораром, оно врало о главном:
 * заработке за месяц. Награда «Полмиллиона за мѣсяцъ» сходилась не потому,
 * что человѣкъ столько заработалъ, а потому, что через него прошли чужія
 * деньги.
 *
 * Поэтому счёту ставится пометка «под проект», и всё, что на нём происходит,
 * выпадает из личных цифр: дохода, расхода, чистого капитала, прогноза,
 * советов и наград. Остаток счёта при этом виден, операции ведутся как
 * обычно, и по проекту показывается своя сводка.
 *
 * Одно исключение, и оно принципиально. Перевод между проектным и личным
 * счётом остаётся: деньги в этот миг действительно перешли границу, и личный
 * остаток обязан это отразить. Доходом перевод не считается — ни здесь, ни
 * где-либо ещё в программе. Свой гонорар вы заводите отдельной записью
 * дохода, когда сами решите, что он ваш.
 */

/** Счёт заведён под проект: деньги на нём чужие. */
export const проектный = (a: Account): boolean => !!a.project

/** Ид проектных счетов, включая архивные: архив не делает деньги вашими. */
export const проектныеИды = (data: VaultData): Set<string> =>
  new Set(data.accounts.filter(проектный).map((a) => a.id))

/**
 * Операция целиком принадлежит проекту и в личных цифрах не участвует.
 *
 * Перевод исключается только когда проектные обе стороны: перекладывание
 * внутри проекта. Перевод наружу или внутрь — движение через границу, его
 * личный остаток обязан видеть.
 */
export function проектная(t: Transaction, иды: Set<string>): boolean {
  if (!иды.size) return false
  if (t.kind === 'transfer') return иды.has(t.accountId) && иды.has(t.toAccountId ?? '')
  return иды.has(t.accountId)
}

// Проекция считается один раз на снимок данных: её просят почти все панели,
// а данные меняются реже, чем перерисовывается окно.
const кэшъ = new WeakMap<VaultData, VaultData>()

/**
 * Вид хранилища без проектных денег — то, что человѣкъ вправе звать своим.
 *
 * Когда проектных счетов нет, возвращается тот же самый объект. Это не
 * бережливость ради бережливости: половина панелей запоминает вычисления по
 * ссылке на `data.transactions`, и новый массив на каждый вызов пересчитывал
 * бы всё окно впустую.
 */
export function личное(data: VaultData): VaultData {
  const иды = проектныеИды(data)
  if (!иды.size) return data
  const было = кэшъ.get(data)
  if (было) return было
  const итогъ: VaultData = {
    ...data,
    accounts: data.accounts.filter((a) => !проектный(a)),
    transactions: data.transactions.filter((t) => !проектная(t, иды)),
  }
  кэшъ.set(data, итогъ)
  return итогъ
}

export interface Трата {
  categoryId: string | null
  amount: Money
}

export interface Проектъ {
  acc: Account
  /** Приходы на проектный счёт: собранные под проект деньги. */
  пришло: Money
  /** Расходы со счёта: на что проект потрачен. */
  потрачено: Money
  /** Переводы с личных счетов на проектный: вложили своих. */
  внесено: Money
  /** Переводы с проектного на личные: взяли себе. */
  выведено: Money
  /** Сколько лежит сейчас. Ниже нуля — проект ушёл в минус. */
  остатокъ: Money
  /** Куда ушли деньги проекта — по статьям, крупные впереди. */
  статьи: Трата[]
  /** Доля израсходованного от собранного, 0..1. */
  освоено: number
}

export function projectState(acc: Account, data: VaultData): Проектъ {
  const иды = проектныеИды(data)
  let пришло = 0
  let потрачено = 0
  let внесено = 0
  let выведено = 0
  const поСтатьямъ = new Map<string | null, Money>()

  for (const t of data.transactions) {
    if (t.kind === 'income' && t.accountId === acc.id) пришло += t.amount
    else if (t.kind === 'expense' && t.accountId === acc.id) {
      потрачено += t.amount
      const k = t.categoryId ?? null
      поСтатьямъ.set(k, (поСтатьямъ.get(k) ?? 0) + t.amount)
    } else if (t.kind === 'transfer') {
      // Перекладывание внутри проекта в сводку не идёт: денег не прибавилось.
      if (t.toAccountId === acc.id && !иды.has(t.accountId)) внесено += t.amount
      else if (t.accountId === acc.id && !иды.has(t.toAccountId ?? '')) выведено += t.amount
    }
  }

  const статьи = [...поСтатьямъ.entries()]
    .map(([categoryId, amount]) => ({ categoryId, amount }))
    .sort((a, b) => b.amount - a.amount)

  const собрано = пришло + внесено
  return {
    acc,
    пришло, потрачено, внесено, выведено,
    остатокъ: accountBalance(acc, data.transactions),
    статьи,
    освоено: собрано > 0 ? Math.min(1, потрачено / собрано) : 0,
  }
}

/** Все проектные счета, кроме убранных в архив. */
export const projectAccounts = (data: VaultData): Account[] =>
  data.accounts.filter((a) => !a.archived && проектный(a))

/** Сводка по всем проектам разом — для дашборда. */
export function projectsSummary(data: VaultData) {
  const все = projectAccounts(data).map((a) => projectState(a, data))
  return {
    список: все,
    пришло: все.reduce((s, p) => s + p.пришло, 0),
    потрачено: все.reduce((s, p) => s + p.потрачено, 0),
    выведено: все.reduce((s, p) => s + p.выведено, 0),
    остатокъ: все.reduce((s, p) => s + p.остатокъ, 0),
  }
}
