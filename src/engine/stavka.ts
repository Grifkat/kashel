/*
 * Ставка по кредиту, когда её не сказали.
 *
 * Банк не всегда пишет процент, но всегда пишет сумму, платёж и срок — а
 * этого довольно: платёж аннуитета связан со ставкой одной формулой
 *
 *     платёж = долг · r / (1 − (1 + r)^−n),   r — ставка за месяц.
 *
 * Обратно r из неё не выражается, поэтому подбираем делением отрезка: левая
 * ставка заведомо мала, правая заведомо велика, и мы половиним
 * промежуток, пока платёж не сойдётся с точностью до копейки. Сорок делений
 * дают точность, которой хватает с запасом, и работают мгновенно.
 */
import type { Account, Money, VaultData } from '../lib/types'
import { creditRemaining } from './stats'
import { today } from '../lib/date'

/** Платёж аннуитета: долг, месячная ставка (доля) и число платежей. */
export function платёжАннуитета(долг: Money, r: number, n: number): Money {
  if (n <= 0) return 0
  if (r <= 0) return долг / n
  return (долг * r) / (1 - Math.pow(1 + r, -n))
}

const ДЕЛЕНИЙ = 60
/** Выше этой месячной ставки (≈1000% годовых) считать нечего. */
const ПОТОЛОКЪ = 1000 / 12 / 100

/**
 * Годовая ставка по долгу, платежу и числу платежей. null — по этим числам
 * ставки нет: платежей не хватает даже на сам долг (или их меньше двух).
 */
export function подобратьСтавку(долг: Money, платёж: Money, n: number): number | null {
  if (!(долг > 0) || !(платёж > 0) || !(n > 0)) return null
  const всего = платёж * n
  // Ровно столько же или меньше — ставка нулевая либо отрицательная.
  if (всего <= долг + 0.5) return null
  if (платёжАннуитета(долг, ПОТОЛОКЪ, n) < платёж) return null
  let низ = 0
  let верх = ПОТОЛОКЪ
  for (let i = 0; i < ДЕЛЕНИЙ; i++) {
    const середина = (низ + верх) / 2
    if (платёжАннуитета(долг, середина, n) < платёж) низ = середина
    else верх = середина
  }
  const годовая = ((низ + верх) / 2) * 12 * 100
  return Math.round(годовая * 100) / 100
}

export interface Прикидка {
  /** Годовая ставка, %. */
  ставка: number
  долг: Money
  платёж: Money
  платежей: number
  /** Сколько выйдет сверх долга за эти платежи. */
  переплата: Money
  /** По чему считали: по договору (сумма и срок) или по остатку долга. */
  по: 'contract' | 'left'
}

/**
 * Прикидка ставки по тому, что уже заполнено у кредита.
 *
 * Сумма кредита и срок — числа договора, по ним ставка выходит точной, и
 * берём их первыми. Если суммы нет (кредит завели уже наполовину
 * выплаченным), считаем по остатку: столько платежей по нему и осталось.
 * Срок в этом случае не годится — по нему платежей выходит больше, чем
 * человеку в самом деле платить, и ставка вышла бы завышенной.
 */
export function прикидкаСтавки(acc: Account, data: VaultData, now: string = today()): Прикидка | null {
  const c = acc.credit
  if (!c || !(c.monthlyPayment > 0)) return null
  void now
  const поДоговору = c.principal > 0 && c.termMonths > 0
  const остаток = creditRemaining(acc, data.transactions)
  const долг = поДоговору ? c.principal : остаток
  const платежей = поДоговору ? c.termMonths : Math.ceil(остаток / c.monthlyPayment)
  const ставка = подобратьСтавку(долг, c.monthlyPayment, платежей)
  if (ставка == null || ставка <= 0) return null
  return {
    ставка, долг, платёж: c.monthlyPayment, платежей,
    переплата: Math.round(c.monthlyPayment * платежей - долг),
    по: поДоговору ? 'contract' : 'left',
  }
}
