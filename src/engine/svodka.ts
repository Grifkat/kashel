import { creditsSummary } from './credit'
import { личное, projectsSummary } from './project'

/*
 * Что уходит к нейросети.
 *
 * Два вида. Сводка — итоги: остатки, суммы по статьям и месяцам, кредиты,
 * цели. Полная выгрузка — всё до последней покупки с комментарием, заметки,
 * задачи. Собрано в одном файле нарочно: что видит модель, должно читаться
 * целиком за минуту, а не выискиваться по разметке.
 *
 * Полная выгрузка появилась по прямой просьбе, и вот на каком основании она
 * допустима. Модель работает на этой же машине, наружу не уходит ничего, и
 * скрывать данные от собственного компьютера смысла нет.
 *
 * Плата за неё — не приватность, а верность ответа, и это измерено, а не
 * предположено. Qwen 3.5 на девять миллиардов весов: получив одни итоги
 * (около 2 900 знаков), она назвала три главные статьи расходов верно за
 * девять секунд; получив всё целиком (74 000 знаков) — неверно, дважды
 * подряд и каждый раз по-новому, хотя верные числа лежали в том же тексте
 * выше и были помечены как готовые. Модель втрое крупнее (qwen3.6:35b-a3b)
 * на том же тексте ошиблась так же, а по одним итогам ответила верно, число
 * в число, — значит дело в объёме, а не в размере модели.
 *
 * Отсюда два вида, а не один: по умолчанию уходит всё, итоги — переключатель
 * для вопросов «сколько» и «что крупнее», а предупреждение показывается,
 * когда выгрузка перевалила за порог. В программе о деньгах уверенно
 * названная неправильная сумма хуже отказа.
 *
 * Числа даются в рублях, а не в копейках, — модель складывает их хуже,
 * чем читает.
 *
 * Проектные счета исключены наравне с остальным учётом: чужие деньги не ваши
 * и разбирать их незачем.
 */

/** Сколько статей и месяцев показывать. Длиннее — модель тонет в перечислении. */
const СТАТЕЙ = 12
const МѢСЯЦЕВЪ = 12
const МѢТОКЪ = 8

const рубли = (к: number) => Math.round(к / 100)

export interface Сводка {
  текстъ: string
  /** Из чего она собрана — показывается человѣку до отправки. */
  строкъ: number
  знаковъ: number
}

export function сводкаДляМодели(данные: VaultData, now: string = today()): Сводка {
  const д = личное(данные)
  const строки: string[] = []
  const п = (s: string) => строки.push(s)

  п('# Сводка по личным финансам')
  п(`Сегодня: ${now}. Валюта: рубли. Все суммы — рубли, не копейки.`)
  п('')

  // ---------------------------------------------------------------- счета
  const бал = balances(д.accounts, д.transactions)
  п('## Счета')
  п(`Активы: ${рубли(бал.assets)}. Обязательства: ${рубли(бал.liabilities)}. Чистый капитал: ${рубли(бал.net)}.`)
  for (const a of д.accounts.filter((x) => !x.archived)) {
    п(`- ${a.name} (${a.type}): ${рубли(бал.byAccount.get(a.id) ?? 0)}`)
  }
  п('')

  // ------------------------------------------------------------- по месяцам
  const съ = addMonths(now, -МѢСЯЦЕВЪ)
  const мѣсяцы = monthlySeries(д.transactions, съ, now)
  п(`## Доход и расход по месяцам (последние ${мѣсяцы.length})`)
  п('месяц | доход | расход | итог')
  for (const м of мѣсяцы) {
    п(`${м.key} | ${рубли(м.income)} | ${рубли(м.expense)} | ${рубли(м.net)}`)
  }
  п('')

  // --------------------------------------------------------------- статьи
  const съГода = addMonths(now, -12)
  const заГодъ = д.transactions.filter((t) => t.date >= съГода)
  const имя = (id: string) => д.categories.find((c) => c.id === id)?.name ?? 'без статьи'

  const тратыВсего = categoryTotals(заГодъ, 'expense')
  п(`## Расходы по статьям за год (топ ${СТАТЕЙ})`)
  for (const c of тратыВсего.slice(0, СТАТЕЙ)) {
    п(`- ${имя(c.categoryId)}: ${рубли(c.amount)} за ${c.count} операций, ${pct(c.share * 100, 0)} всех трат`)
  }
  п('')

  const доходы = categoryTotals(заГодъ, 'income')
  п('## Доходы по статьям за год')
  for (const c of доходы.slice(0, СТАТЕЙ)) {
    п(`- ${имя(c.categoryId)}: ${рубли(c.amount)} за ${c.count} операций, ${pct(c.share * 100, 0)} всего дохода`)
  }
  п('')

  // --------------------------------------------------------------- планы
  const съПланомъ = д.categories.filter((c) => c.kind === 'expense' && !c.archived && c.plan)
  if (съПланомъ.length) {
    const этотъ = monthKey(now)
    const вМѣсяцѣ = д.transactions.filter((t) => monthKey(t.date) === этотъ)
    const потрачено = new Map(categoryTotals(вМѣсяцѣ, 'expense').map((c) => [c.categoryId, c.amount]))
    п(`## Планы на месяц (${monthTitle(этотъ)})`)
    for (const c of съПланомъ) {
      п(`- ${c.name}: план ${рубли(c.plan!)}, потрачено ${рубли(потрачено.get(c.id) ?? 0)}`)
    }
    п('')
  }

  // -------------------------------------------------------------- кредиты
  const кр = creditsSummary(д)
  if (кр.список.length) {
    п('## Кредиты')
    п(`Всего долг: ${рубли(кр.debt)}. Платежи в месяц: ${рубли(кр.payment)}.`)
    for (const k of кр.список) {
      const срокъ = k.monthsLeft == null
        ? 'платёж не покрывает проценты, долг не гасится'
        : `закроется через ${k.monthsLeft} мес., переплата ${рубли(k.overpay)}`
      п(`- ${k.acc.name}: долг ${рубли(k.debt)}, ставка ${k.ratePct}%, платёж ${рубли(k.payment)} — ${срокъ}`)
    }
    п('')
  }

  // ------------------------------------------------------------- проекты
  const пр = projectsSummary(данные)
  if (пр.список.length) {
    п('## Проектные счета (чужие деньги, в личных цифрах не учтены)')
    for (const p of пр.список) п(`- ${p.acc.name}: остаток ${рубли(p.остатокъ)}`)
    п('')
  }

  // ----------------------------------------------------------------- цели
  const цѣли = д.goals.filter((g) => !g.done)
  if (цѣли.length) {
    п('## Цели')
    for (const g of цѣли) {
      п(`- ${g.name}: нужно ${рубли(g.targetAmount)}, отложено ${рубли(g.saved)}${g.targetDate ? `, срок ${g.targetDate}` : ''}`)
    }
    п('')
  }

  // -------------------------------------------------------------- метки
  const мѣтки = tagTotals(заГодъ, 'expense')
  if (мѣтки.length) {
    п(`## Метки на тратах за год (топ ${МѢТОКЪ})`)
    for (const м of мѣтки.slice(0, МѢТОКЪ)) п(`- ${м.tag}: ${рубли(м.amount)} за ${м.count} операций`)
    п('')
  }

  // ------------------------------------------------------------ регулярные
  const рег = д.recurring.filter((r) => r.active)
  if (рег.length) {
    п('## Регулярные платежи')
    for (const r of рег) п(`- ${r.title}: ${рубли(r.amount)} ${r.freq}, ${r.kind === 'income' ? 'приход' : 'расход'}`)
    п('')
  }

  п('---')
  п('Это итоги, а не выписка. Отдельных покупок, комментариев и заметок здесь нет и не будет.')

  const текстъ = строки.join('\n')
  return { текстъ, строкъ: строки.length, знаковъ: текстъ.length }
}

