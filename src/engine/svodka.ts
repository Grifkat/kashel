/**
 * Напоминание о языке ответа — кладётся прямо перед вопросом.
 *
 * Одного правила в наставлении маленькой модели мало: данные перед вопросом
 * написаны на языке окна, и по-английски спрошенное о русской выгрузке она
 * охотно дописывает по-русски. Ближайшая к вопросу строка перевешивает.
 *
 * Язык угадывается по буквам самого вопроса, а не по языку окна: окно может
 * быть русским, а спросить человек волен как угодно. Поэтому и строка не
 * идёт через т() — она на языке вопроса, а не интерфейса. Латиница — не
 * обязательно английский, так что для неё правило общее: «на языке вопроса».
 */
export function наказЯзыка(вопросъ: string): string {
  const кириллица = (вопросъ.match(/[а-яёѣіѳѵ]/gi) ?? []).length
  const латиница = (вопросъ.match(/[a-z]/gi) ?? []).length
  if (кириллица > латиница) return 'Вопрос задан по-русски. Отвечай по-русски, даже если данные выше или прежние ответы на другом языке.'
  if (латиница > кириллица) return "Answer in the same language as the user's next message (a question in English gets an answer in English), even if the data above or earlier replies are in another language."
  return 'Answer in the language of the question. Отвечай на языке вопроса.'
}

/*
 * Полная выгрузка: всё, что есть в хранилище.
 *
 * Каждая операция с датой, суммой, счётом, статьёй, метками и комментарием;
 * заметки целиком; задачи; напоминания. Ровно то, о чём просили — «чтобы
 * видел вообще всё».
 *
 * Заметки лежат отдельными файлами, поэтому выгрузка асинхронна: их надо
 * прочесть с диска (или из облака). Сводка остаётся синхронной — ей файлы
 * не нужны, и заставлять её ждать было бы незачем.
 *
 * Операции идут таблицей, а не списком: на тысяче строк это вдвое короче,
 * а модель читает разделённые чертой поля не хуже, чем предложения.
 */
export async function полнаяВыгрузка(
  данные: VaultData,
  читатьЗамѣтку?: (имя: string) => Promise<string | null>,
  списокЗамѣтокъ?: () => Promise<string[]>,
  now: string = today(),
): Promise<Сводка> {
  const д = личное(данные)
  /*
   * Итоги идут первыми и помечены как готовые.
   *
   * Проверено вживую и вышло скверно: получив тысячу строк, и модель на 9
   * миллиардов, и та, что втрое крупнее, принимались складывать их сами и
   * называли три главные статьи расходов неверно — при том, что верные
   * лежали у них же выше. Для
   * программы о деньгах увѣренно названная неправильная сумма хуже отказа.
   * Отсюда и пометка, и наставленіе брать числа отсюда, а перечень операций
   * держать для частностей.
   */
  const строки: string[] = [
    т('# ЧАСТЬ 1. ГОТОВЫЕ ИТОГИ — посчитаны программой, верны, бери суммы отсюда'),
    '',
    сводкаДляМодели(данные, now).текстъ,
    '',
  ]
  const п = (s: string) => строки.push(s)

  const статья = (id?: string) => д.categories.find((c) => c.id === id)?.name ?? ''
  const счётъ = (id?: string) => д.accounts.find((a) => a.id === id)?.name ?? ''
  const видъ = { expense: т('расход'), income: т('приход'), transfer: т('перевод') }

  п(т('# ЧАСТЬ 2. Перечень операций — для частностей, а не для сложения'))
  п(т('Всего: {0}. Суммы в рублях. Общие суммы смотри в части 1.', д.transactions.length))
  п(т('дата | вид | сумма | счёт | статья | метки | комментарий'))
  for (const t of [...д.transactions].sort((a, b) => (a.date < b.date ? -1 : 1))) {
    const куда = t.offBook
      ? (t.offBook === 'in' ? т('извне → {0}', счётъ(t.accountId)) : т('{0} → наружу', счётъ(t.accountId)))
      : t.kind === 'transfer' ? `${счётъ(t.accountId)} → ${счётъ(t.toAccountId)}` : счётъ(t.accountId)
    const доли = t.splits?.length
      ? т(' [доли: ') + t.splits.map((s) => `${статья(s.categoryId)} ${рубли(s.amount)}`).join(', ') + ']'
      : ''
    п([
      t.date, видъ[t.kind], рубли(t.amount), куда, статья(t.categoryId),
      t.tags.join(' '), (t.note ?? '') + доли,
    ].join(' | '))
  }
  п('')

  const задачи = д.tasks ?? []
  if (задачи.length) {
    п(т('# Задачи'))
    for (const з of задачи) {
      const сумма = з.moneyKind === 'time'
        ? (з.minutes ? т(', время {0} мин', з.minutes) : т(', только время'))
        : з.amount ? `, ${рубли(з.amount)} (${з.moneyKind === 'income' ? т('приход') : т('расход')})` : ''
      п(`- ${з.done ? т('[сделано]') : т('[в работе]')} ${з.title}${з.due ? т(', срок {0}', з.due) : ''}${сумма}${з.note ? ` — ${з.note}` : ''}`)
    }
    п('')
  }

  const напоминанія = (д.reminders ?? []).filter((r) => r.active)
  if (напоминанія.length) {
    п(т('# Напоминания'))
    for (const н of напоминанія) п(`- ${н.title}${н.date ? `, ${н.date}` : ''}${н.event ? т(', событие: {0}', н.event) : ''}`)
    п('')
  }

  // Заметки — единственное, за чем приходится ходить на диск.
  if (списокЗамѣтокъ && читатьЗамѣтку) {
    try {
      const имена = await списокЗамѣтокъ()
      if (имена.length) {
        п(т('# Заметки'))
        for (const имя of имена) {
          const тѣло = await читатьЗамѣтку(имя)
          п(`## ${имя}`)
          п(тѣло ?? т('(пусто)'))
          п('')
        }
      }
    } catch {
      // Заметки не достались — выгрузка всё равно осмысленна. Молчать об
      // этом нельзя, поэтому строкой ниже честно говорим, чего в ней нет.
      п(т('# Заметки'))
      п(т('(не удалось прочесть)'))
      п('')
    }
  }

  const текстъ = строки.join('\n')
  return { текстъ, строкъ: строки.length, знаковъ: текстъ.length }
}

