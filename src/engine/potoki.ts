/*
 * Потоки денег: откуда пришли и куда ушли.
 *
 * Схема Санкея за период: статьи дохода → счета → главные категории
 * расходов → подкатегории. Толщина ленты — сумма. Разбитый чек идёт по
 * своим долям. Главная категория раскрывается на подкатегории; то, что
 * записано прямо в главную, идёт строкой «— без подкатегории», как на
 * «Сводке».
 *
 * Переводы между своими счетами — лентами от счёта к счёту. Счёт, который
 * пополняется переводом (наличные, копилка), стоит правее того, откуда
 * пришли деньги, и путь «Зарплата → Карта → Наличные → Кафе» читается
 * слева направо. Встречные переводы сводятся в один, разность.
 *
 * Схема сведена: что пришло на счёт и не ушло, течёт в «Осталось», а что
 * ушло сверх пришедшего — из «Прежних остатков» (у кредитов и долгов — «В
 * долг» и «Погашено»). Поэтому у каждого счёта вход равен выходу, а слева
 * и справа одна и та же сумма.
 *
 * Здесь только счёт, раскладка и след цепочки — без React и без DOM.
 */
import type { Account, Category, Money, Transaction } from '../lib/types'
import { родитель } from './podkategorii'
import { т } from '../i18n'

/** Вид узла: статья дохода, счёт, статья расхода или служебный «запас» («Осталось», «В долг»…). */
export type ВидУзлаПотока = 'income' | 'account' | 'expense' | 'stock'

export interface УзелПотока {
  id: string
  вид: ВидУзлаПотока
  имя: string
  цвет: string
  значок?: string
  /** Столбец слева направо, пустых столбцов нет. */
  столбец: number
  /**
   * Чьи операции открывает щелчок: id категории, счёта или 'uncategorized'.
   * У «запасов» пусто — операций за ними нет.
   */
  ref?: string
  /** Узел счёта, а не категории. */
  счёт?: boolean
  /** Короткая подпись на схеме, если полное имя длинно: «без подкатегории». */
  подпись?: string
  /** У подкатегории — id узла её главной. */
  главная?: string
  /** У главной — сколько подкатегорий с движением за период. */
  подкатегорий?: number
  раскрыта?: boolean
  /** Пришло в узел и ушло из него за период. */
  вход: Money
  выход: Money
}

export interface ЛентаПотока {
  id: string
  из: string
  в: string
  сумма: Money
  /** Доход, расход, перевод, подкатегория → главная (или обратно) и сведение счёта. */
  вид: 'income' | 'expense' | 'transfer' | 'sub' | 'stock'
}

export interface Потоки {
  /** По столбцам слева направо, внутри столбца — сверху вниз. */
  узлы: УзелПотока[]
  ленты: ЛентаПотока[]
  /** Доходы и расходы за период — без переводов и «запасов». */
  пришло: Money
  ушло: Money
  столбцов: number
}

export interface ПараметрыПотоков {
  transactions: Transaction[]
  categories: Category[]
  accounts: Account[]
  /** С какого дня, включительно; пусто — за всё время. */
  с: string
  /** Показывать переводы между своими счетами. */
  переводы: boolean
  /** Главные категории, чьи подкатегории свёрнуты. */
  свёрнуты: ReadonlySet<string>
}

/** Сколько денег прошло через узел: у счёта вход равен выходу, у прочих — бо́льшее. */
export const черезУзел = (у: УзелПотока): Money => Math.max(у.вход, у.выход)

const СЕРЫЙ = '#8b95a5'
/** Доли операции по статьям: разбитый чек — по своим долям. */
const доли = (t: Transaction): { categoryId?: string; amount: Money }[] =>
  t.splits?.length ? t.splits : [{ categoryId: t.categoryId, amount: t.amount }]

export function потоки(п: ПараметрыПотоков): Потоки {
  const cats = п.categories
  const катПоId = new Map(cats.map((c) => [c.id, c]))
  const счётПоId = new Map(п.accounts.map((a) => [a.id, a]))

  // ------------------------------------------------ суммы по статьям и счетам
  type Сторона = 'i' | 'e'
  /** сторона|категория|счёт → сумма */
  const статьи = new Map<string, Money>()
  /** Переводы, сведённые по парам: «меньший id|больший id» → со знаком. */
  const переводы = new Map<string, Money>()
  let пришло = 0
  let ушло = 0
  for (const t of п.transactions) {
    if (п.с && t.date < п.с) continue
    if (t.kind === 'transfer') {
      const к = t.toAccountId
      if (!п.переводы || !к || к === t.accountId) continue
      const [a, b] = t.accountId < к ? [t.accountId, к] : [к, t.accountId]
      переводы.set(a + '|' + b, (переводы.get(a + '|' + b) ?? 0) + (a === t.accountId ? t.amount : -t.amount))
      continue
    }
    const сторона: Сторона = t.kind === 'income' ? 'i' : 'e'
    if (сторона === 'i') пришло += t.amount
    else ушло += t.amount
    for (const д of доли(t)) {
      if (д.amount <= 0) continue
      const id = д.categoryId && катПоId.has(д.categoryId) ? д.categoryId : ''
      const ключ = `${сторона}|${id}|${t.accountId}`
      статьи.set(ключ, (статьи.get(ключ) ?? 0) + д.amount)
    }
  }

  // Главная и подкатегории с движением за период — раскрывать есть что.
  const главнаяId = (id: string) => {
    const c = катПоId.get(id)
    return (c && родитель(c, cats)?.id) || id
  }
  const подкатегорииС = new Map<string, Set<string>>()
  for (const ключ of статьи.keys()) {
    const [сторона, id] = ключ.split('|')
    const г = id ? главнаяId(id) : ''
    if (id && г !== id) {
      const к = сторона + '|' + г
      подкатегорииС.set(к, (подкатегорииС.get(к) ?? new Set()).add(id))
    }
  }
  const раскрыта = (сторона: string, г: string) => !п.свёрнуты.has(г) && !!подкатегорииС.get(сторона + '|' + г)?.size

  // ------------------------------------------------ ленты
  const ленты = new Map<string, ЛентаПотока>()
  const течь = (из: string, в: string, сумма: Money, вид: ЛентаПотока['вид']) => {
    if (сумма <= 0 || из === в) return
    const id = из + '>' + в
    const л = ленты.get(id)
    if (л) л.сумма += сумма
    else ленты.set(id, { id, из, в, сумма, вид })
  }
  const узелСтатьи = (сторона: Сторона, id: string) => (id ? `${сторона}:${id}` : `${сторона}:__none__`)
  for (const [ключ, сумма] of статьи) {
    const [сторона, id, accId] = ключ.split('|') as [Сторона, string, string]
    const г = id ? главнаяId(id) : ''
    const счёт = 'acc:' + accId
    const группа = узелСтатьи(сторона, г)
    // Раскрытая главная: подкатегория (или «без подкатегории») — отдельный узел.
    const мелкий = г && раскрыта(сторона, г) ? (id === г ? `${сторона}o:${г}` : узелСтатьи(сторона, id)) : ''
    if (сторона === 'i') {
      if (мелкий) течь(мелкий, группа, сумма, 'sub')
      течь(группа, счёт, сумма, 'income')
    } else {
      течь(счёт, группа, сумма, 'expense')
      if (мелкий) течь(группа, мелкий, сумма, 'sub')
    }
  }

  // Переводы: встречные сведены; круг из трёх и больше счетов рвётся на
  // самом мелком переводе — схема течёт только слева направо.
  const рёбра: { из: string; в: string; сумма: Money }[] = []
  for (const [пара, сумма] of переводы) {
    const [a, b] = пара.split('|')
    if (сумма > 0) рёбра.push({ из: a, в: b, сумма })
    else if (сумма < 0) рёбра.push({ из: b, в: a, сумма: -сумма })
  }
  const глубина = new Map<string, number>()
  {
    const живые = [...рёбра].sort((x, y) => y.сумма - x.сумма)
    for (;;) {
      // Кан: счета без входящих переводов — первые.
      const входящих = new Map<string, number>()
      const все = new Set<string>()
      for (const р of живые) {
        все.add(р.из).add(р.в)
        входящих.set(р.в, (входящих.get(р.в) ?? 0) + 1)
      }
      const очередь = [...все].filter((x) => !входящих.get(x))
      const пройдены = new Set<string>()
      while (очередь.length) {
        const x = очередь.shift()!
        пройдены.add(x)
        for (const р of живые) {
          if (р.из !== x) continue
          глубина.set(р.в, Math.max(глубина.get(р.в) ?? 0, (глубина.get(x) ?? 0) + 1))
          входящих.set(р.в, входящих.get(р.в)! - 1)
          if (!входящих.get(р.в)) очередь.push(р.в)
        }
      }
      if (пройдены.size === все.size) break
      // Остался круг: самый мелкий перевод внутри него в схему не идёт.
      const вКруге = живые.filter((р) => !пройдены.has(р.из) && !пройдены.has(р.в))
      живые.splice(живые.indexOf(вКруге[вКруге.length - 1]), 1)
      глубина.clear()
    }
    for (const р of живые) течь('acc:' + р.из, 'acc:' + р.в, р.сумма, 'transfer')
  }

  // ------------------------------------------------ сведение счетов
  const вход = new Map<string, Money>()
  const выход = new Map<string, Money>()
  const счесть = () => {
    вход.clear()
    выход.clear()
    for (const л of ленты.values()) {
      выход.set(л.из, (выход.get(л.из) ?? 0) + л.сумма)
      вход.set(л.в, (вход.get(л.в) ?? 0) + л.сумма)
    }
  }
  счесть()
  const счетаВСхеме = new Set<string>()
  for (const л of ленты.values()) {
    if (л.из.startsWith('acc:')) счетаВСхеме.add(л.из)
    if (л.в.startsWith('acc:')) счетаВСхеме.add(л.в)
  }
  for (const id of счетаВСхеме) {
    const разница = (вход.get(id) ?? 0) - (выход.get(id) ?? 0)
    const долг = ['credit', 'debt'].includes(счётПоId.get(id.slice(4))?.type ?? '')
    if (разница > 0) течь(id, долг ? 'repaid' : 'left', разница, 'stock')
    else if (разница < 0) течь(долг ? 'loan' : 'stock', id, -разница, 'stock')
  }
  счесть()

  // ------------------------------------------------ узлы и столбцы
  const сколькоГлубин = Math.max(0, ...глубина.values())
  const id2узел = new Map<string, УзелПотока>()
  const узел = (id: string): УзелПотока => {
    const есть = id2узел.get(id)
    if (есть) return есть
    const у: УзелПотока = { id, вид: 'stock', имя: '', цвет: СЕРЫЙ, столбец: 0, вход: вход.get(id) ?? 0, выход: выход.get(id) ?? 0 }
    if (id.startsWith('acc:')) {
      const a = счётПоId.get(id.slice(4))
      Object.assign(у, { вид: 'account', имя: a?.name ?? т('Счёт'), цвет: a?.color || '#4cc46a', значок: a?.icon, ref: id.slice(4), счёт: true, столбец: 2 + (глубина.get(id.slice(4)) ?? 0) })
    } else if (id === 'stock' || id === 'loan') {
      Object.assign(у, { имя: id === 'stock' ? т('Из прежних остатков') : т('В долг'), цвет: id === 'stock' ? 'var(--muted)' : 'var(--money-out)', столбец: 1 })
    } else if (id === 'left' || id === 'repaid') {
      Object.assign(у, { имя: id === 'left' ? т('Осталось') : т('Погашено'), цвет: id === 'left' ? 'var(--money-in)' : 'var(--muted)', столбец: 3 + сколькоГлубин })
    } else {
      const сторона = id[0] as Сторона
      const свой = id[1] === 'o'
      const catId = id.slice(id.indexOf(':') + 1)
      const главная = свой ? catId : catId === '__none__' ? '' : главнаяId(catId)
      const c = катПоId.get(catId)
      const мелкий = свой || (!!главная && главная !== catId)
      const столбец = сторона === 'i' ? (мелкий ? 0 : 1) : 3 + сколькоГлубин + (мелкий ? 1 : 0)
      Object.assign(у, {
        вид: сторона === 'i' ? 'income' : 'expense',
        имя: catId === '__none__' ? т('Без категории') : свой ? т('{0} — без подкатегории', c?.name ?? '') : c?.name ?? '',
        цвет: c?.color || СЕРЫЙ,
        значок: свой ? undefined : c?.icon,
        ref: catId === '__none__' ? 'uncategorized' : catId,
        ...(свой ? { подпись: т('без подкатегории') } : {}),
        столбец,
        ...(мелкий ? { главная: `${сторона}:${главная}` } : {}),
      })
      const подкатегорий = !мелкий && главная ? подкатегорииС.get(сторона + '|' + главная)?.size ?? 0 : 0
      if (подкатегорий) Object.assign(у, { подкатегорий, раскрыта: раскрыта(сторона, главная) })
    }
    id2узел.set(id, у)
    return у
  }
  for (const л of ленты.values()) {
    узел(л.из)
    узел(л.в)
  }

  // Пустые столбцы сжимаются: без подкатегорий и переводов схема уже.
  const занятые = [...new Set([...id2узел.values()].map((у) => у.столбец))].sort((a, b) => a - b)
  for (const у of id2узел.values()) у.столбец = занятые.indexOf(у.столбец)

  // Порядок в столбце: крупные выше, служебные — внизу, подкатегории — под
  // своей главной в том же порядке, что и главные.
  const служебный = (у: УзелПотока) => (у.вид === 'stock' ? 2 : у.ref === 'uncategorized' ? 1 : 0)
  const все = [...id2узел.values()]
  const место = new Map<string, number>()
  const поСтолбцам = (a: УзелПотока, b: УзелПотока) =>
    a.столбец - b.столбец || служебный(a) - служебный(b) || черезУзел(b) - черезУзел(a) || a.имя.localeCompare(b.имя)
  // главные — сначала, чтобы подкатегории могли встать по их порядку
  const главные = все.filter((у) => !у.главная).sort(поСтолбцам)
  главные.forEach((у, i) => место.set(у.id, i))
  const мелкие = все.filter((у) => у.главная).sort((a, b) =>
    a.столбец - b.столбец || (место.get(a.главная!) ?? 0) - (место.get(b.главная!) ?? 0)
    || Number(a.id[1] === 'o') - Number(b.id[1] === 'o') || черезУзел(b) - черезУзел(a))
  const узлы = [...главные, ...мелкие].sort((a, b) => a.столбец - b.столбец)
  // sort устойчив: внутри столбца остаётся порядок, выставленный выше

  return {
    узлы,
    ленты: [...ленты.values()],
    пришло,
    ушло,
    столбцов: занятые.length,
  }
}

// ------------------------------------------------------------------ раскладка

export interface Рамка { x: number; y: number; w: number; h: number }

export interface МестоУзла { x: number; y: number; h: number }
export interface МестоЛенты { x0: number; x1: number; y0: number; y1: number; t: number }

export interface РаскладкаПотоков {
  узлы: Map<string, МестоУзла>
  ленты: Map<string, МестоЛенты>
  /** Ширина полосы узла. */
  полоса: number
  /** Сколько пикселей на копейку. */
  масштаб: number
  /** x столбцов. */
  столбцы: number[]
}

/**
 * Раскладка в рамке. Промежуток между столбцами — сколько просят подписи
 * в нём (промежутки[i] — между столбцами i и i + 1), а остаток ширины
 * делится поровну; не хватает ширины на всех — каждому по доле. Узлы в
 * столбце — сверху вниз с зазорами, высота — по сумме, общей для всех
 * столбцов. Ленты пристыкованы к узлу в порядке узла на другом конце — так
 * они не перекрещиваются у самого узла.
 */
export function разложитьПотоки(п: Потоки, рамка: Рамка, полоса = 12, промежутки: number[] = []): РаскладкаПотоков {
  const столбцы: УзелПотока[][] = Array.from({ length: п.столбцов }, () => [])
  for (const у of п.узлы) столбцы[у.столбец]?.push(у)
  const щелей = Math.max(0, п.столбцов - 1)
  const свободно = Math.max(0, рамка.w - полоса * п.столбцов)
  const просят = Array.from({ length: щелей }, (_, i) => Math.max(0, промежутки[i] ?? 0))
  const всего = просят.reduce((s, x) => s + x, 0)
  const доля = всего > свободно ? свободно / всего : 1
  const сверх = щелей ? Math.max(0, свободно - всего) / щелей : 0
  const xs: number[] = []
  for (let i = 0; i < п.столбцов; i++) {
    xs.push(i === 0 ? (щелей ? рамка.x : рамка.x + (рамка.w - полоса) / 2) : xs[i - 1] + полоса + просят[i - 1] * доля + сверх)
  }

  const основа = Math.max(6, Math.min(18, рамка.h * 0.035))
  const зазор = (n: number) => (n > 1 ? Math.min(основа, (рамка.h * 0.35) / (n - 1)) : 0)
  let масштаб = Infinity
  for (const с of столбцы) {
    const сумма = с.reduce((s, у) => s + черезУзел(у), 0)
    if (сумма > 0) масштаб = Math.min(масштаб, (рамка.h - зазор(с.length) * (с.length - 1)) / сумма)
  }
  if (!isFinite(масштаб) || масштаб < 0) масштаб = 0

  const узлы = new Map<string, МестоУзла>()
  столбцы.forEach((с, i) => {
    const высоты = с.map((у) => Math.max(2, черезУзел(у) * масштаб))
    const з = зазор(с.length)
    const всего = высоты.reduce((s, h) => s + h, 0) + з * Math.max(0, с.length - 1)
    let y = рамка.y + Math.max(0, (рамка.h - всего) / 2)
    с.forEach((у, j) => {
      узлы.set(у.id, { x: xs[i], y, h: высоты[j] })
      y += высоты[j] + з
    })
  })
  // Подкатегории встают напротив своей главной, а не посреди столбца: тогда
  // ленты от главной к ним идут почти прямо. Наложения раздвигаются вниз,
  // а что не влезло — поднимается снизу.
  столбцы.forEach((с) => {
    if (!с.length || !с.every((у) => у.главная)) return
    const з = зазор(с.length)
    const места = с.map((у) => узлы.get(у.id)!)
    let прежняя = ''
    let y = 0
    с.forEach((у, j) => {
      if (у.главная !== прежняя) y = узлы.get(у.главная!)?.y ?? места[j].y
      прежняя = у.главная!
      места[j].y = y
      y += места[j].h + з
    })
    for (let j = 1; j < места.length; j++) места[j].y = Math.max(места[j].y, места[j - 1].y + места[j - 1].h + з)
    const низ = рамка.y + рамка.h
    const последний = места[места.length - 1]
    if (последний.y + последний.h > низ) {
      последний.y = низ - последний.h
      for (let j = места.length - 2; j >= 0; j--) места[j].y = Math.min(места[j].y, места[j + 1].y - з - места[j].h)
    }
    if (места[0].y < рамка.y) {
      места[0].y = рамка.y
      for (let j = 1; j < места.length; j++) места[j].y = Math.max(места[j].y, места[j - 1].y + места[j - 1].h + з)
    }
  })

  const центр = (id: string) => {
    const м = узлы.get(id)
    return м ? м.y + м.h / 2 : 0
  }
  const ленты = new Map<string, МестоЛенты>()
  const исходящие = new Map<string, ЛентаПотока[]>()
  const входящие = new Map<string, ЛентаПотока[]>()
  for (const л of п.ленты) {
    исходящие.set(л.из, [...(исходящие.get(л.из) ?? []), л])
    входящие.set(л.в, [...(входящие.get(л.в) ?? []), л])
  }
  const толщина = (л: ЛентаПотока) => Math.max(0.8, л.сумма * масштаб)
  const y0 = new Map<string, number>()
  const y1 = new Map<string, number>()
  for (const [id, сп] of исходящие) {
    let y = узлы.get(id)?.y ?? 0
    for (const л of [...сп].sort((a, b) => центр(a.в) - центр(b.в))) {
      y0.set(л.id, y + толщина(л) / 2)
      y += толщина(л)
    }
  }
  for (const [id, сп] of входящие) {
    let y = узлы.get(id)?.y ?? 0
    for (const л of [...сп].sort((a, b) => центр(a.из) - центр(b.из))) {
      y1.set(л.id, y + толщина(л) / 2)
      y += толщина(л)
    }
  }
  for (const л of п.ленты) {
    const a = узлы.get(л.из)
    const b = узлы.get(л.в)
    if (!a || !b) continue
    ленты.set(л.id, { x0: a.x + полоса, x1: b.x, y0: y0.get(л.id)!, y1: y1.get(л.id)!, t: толщина(л) })
  }
  return { узлы, ленты, полоса, масштаб, столбцы: xs }
}

const д = (v: number) => Math.round(v * 10) / 10

/** Лента — полоса постоянной высоты между двумя узлами, изогнутая мягкой S-кривой. */
export function путьЛенты(м: МестоЛенты, доля = 1): string {
  const t = м.t * доля
  const xm = д((м.x0 + м.x1) / 2)
  const [x0, x1] = [д(м.x0), д(м.x1)]
  const [a0, a1, b0, b1] = [д(м.y0 - t / 2), д(м.y1 - t / 2), д(м.y0 + t / 2), д(м.y1 + t / 2)]
  return `M${x0},${a0}C${xm},${a0} ${xm},${a1} ${x1},${a1}L${x1},${b1}C${xm},${b1} ${xm},${b0} ${x0},${b0}Z`
}

// ------------------------------------------------------------------ след

/** С чего начинается след: узел или лента. */
export interface Семя { вид: 'node' | 'link'; id: string }

export interface След {
  /** Сколько из ленты относится к выбранному. */
  ленты: Map<string, Money>
  /** Сколько денег узла относится к выбранному. */
  узлы: Map<string, Money>
}

/**
 * След цепочки: откуда пришли деньги узла или ленты и куда они ушли.
 *
 * На счёте деньги смешиваются, поэтому след делится по долям: если
 * треть денег карты — навар, то и треть трат с карты на кафе — навар. Вверх
 * по схеме доля считается от того, сколько узел отдал выбранному, вниз — от
 * того, сколько он от выбранного получил.
 */
export function проследить(п: Потоки, семя: Семя): След {
  const поId = new Map(п.узлы.map((у) => [у.id, у]))
  const ленты = new Map<string, Money>()
  const нужно = new Map<string, Money>()
  const дано = new Map<string, Money>()
  if (семя.вид === 'node') {
    const у = поId.get(семя.id)
    if (!у) return { ленты, узлы: new Map() }
    нужно.set(у.id, черезУзел(у))
    дано.set(у.id, черезУзел(у))
  } else {
    const л = п.ленты.find((x) => x.id === семя.id)
    if (!л) return { ленты, узлы: new Map() }
    ленты.set(л.id, л.сумма)
    нужно.set(л.из, л.сумма)
    дано.set(л.в, л.сумма)
  }
  const столбец = (id: string) => поId.get(id)?.столбец ?? 0
  const вверх = [...п.ленты].sort((a, b) => столбец(b.в) - столбец(a.в))
  for (const л of вверх) {
    const н = нужно.get(л.в)
    if (!н) continue
    const ч = черезУзел(поId.get(л.в)!)
    const доля = ч ? (л.сумма * н) / ч : 0
    if (доля <= 0) continue
    ленты.set(л.id, (ленты.get(л.id) ?? 0) + доля)
    нужно.set(л.из, (нужно.get(л.из) ?? 0) + доля)
  }
  const вниз = [...п.ленты].sort((a, b) => столбец(a.из) - столбец(b.из))
  for (const л of вниз) {
    const д = дано.get(л.из)
    if (!д) continue
    const ч = черезУзел(поId.get(л.из)!)
    const доля = ч ? (л.сумма * д) / ч : 0
    if (доля <= 0) continue
    ленты.set(л.id, (ленты.get(л.id) ?? 0) + доля)
    дано.set(л.в, (дано.get(л.в) ?? 0) + доля)
  }
  const узлы = new Map<string, Money>()
  for (const [id, v] of нужно) узлы.set(id, v)
  for (const [id, v] of дано) узлы.set(id, Math.max(узлы.get(id) ?? 0, v))
  return { ленты, узлы }
}
