import type { VaultData } from '../lib/types'
import { addDays, monthKey, parseISO, today } from '../lib/date'

/*
 * Серія: сколько дней подрядъ въ хранилище появлялась запись.
 *
 * Голая серія «пропустилъ день — потерялъ всё» въ учётѣ денегъ работаетъ
 * противъ себя. Человѣкъ, у котораго за полгода накопилось сто восемьдесятъ
 * дней, послѣ одной забытой субботы теряетъ поводъ продолжать вовсе. Поэтому
 * тутъ два послабленія, и оба — заранѣе объявленныя, а не тайныя:
 *
 *  1. Двѣ заморозки въ календарный мѣсяцъ. Пропущенный день закрывается самъ,
 *     если запасъ мѣсяца не исчерпанъ. Третій пропускъ рветъ серію.
 *  2. Выходной — день недѣли, выбранный человѣкомъ. Онъ серію не наращиваетъ
 *     и не рветъ: его просто нѣтъ въ счётѣ.
 *
 * Сегодняшній день особый: пока онъ не кончился, отсутствіе записи не считается
 * пропускомъ. Иначе серія обнулялась бы каждое утро.
 */

/** Сколько пропусковъ въ мѣсяцѣ закрывается само. */
export const FREEZES_PER_MONTH = 2

export interface Streak {
  /** Длина текущей серіи въ дняхъ. */
  days: number
  /** Самая длинная серія за всё время. */
  best: number
  /** Сколько заморозокъ уже потрачено въ текущемъ мѣсяцѣ. */
  freezesUsed: number
  /** Сколько осталось до конца мѣсяца. */
  freezesLeft: number
  /** Записана ли запись за сегодня. */
  todayDone: boolean
  /** Выбранный выходной, 0 — воскресенье. null — выходного нѣтъ. */
  restDay: number | null
  /** Первый день текущей серіи. Пусто — серіи нѣтъ. */
  since: string | null
}

const пустая = (restDay: number | null): Streak => ({
  days: 0, best: 0, freezesUsed: 0, freezesLeft: FREEZES_PER_MONTH,
  todayDone: false, restDay, since: null,
})

/**
 * Считаетъ серію однимъ проходомъ отъ первой записи до сегодня.
 *
 * Одинъ проходъ, а не два: текущая длина и рекордъ должны считаться по одному
 * и тому же правилу, иначе рекордъ окажется недостижимъ для текущей серіи.
 */
export function streak(data: VaultData, now: string = today()): Streak {
  const restDay = data.settings?.restDay ?? null
  const дни = new Set(data.transactions.map((t) => t.date))
  if (!дни.size) return пустая(restDay)

  const первый = [...дни].reduce((min, d) => (d < min ? d : min))
  if (первый > now) return пустая(restDay)

  let текущая = 0
  let рекордъ = 0
  let началоТекущей: string | null = null
  let мѣсяцъ = ''
  let заморозки = 0

  for (let d = первый; d <= now; d = addDays(d, 1)) {
    const мк = monthKey(d)
    if (мк !== мѣсяцъ) { мѣсяцъ = мк; заморозки = 0 }

    // Выходного въ счётѣ просто нѣтъ: он не наращиваетъ серію и не рветъ её.
    if (restDay != null && parseISO(d).getDay() === restDay) continue

    if (дни.has(d)) {
      if (текущая === 0) началоТекущей = d
      текущая++
      if (текущая > рекордъ) рекордъ = текущая
      continue
    }

    // Сегодня ещё не кончилось — отсутствіе записи пропускомъ не считаемъ.
    if (d === now) break

    // Тратить заморозку не на что, пока серіи нѣтъ: до первой записи и послѣ
    // обрыва пропуски проходятъ даромъ, иначе запасъ мѣсяца сгоралъ бы впустую.
    if (текущая === 0) continue

    if (заморозки < FREEZES_PER_MONTH) {
      заморозки++
      // Заморозка держитъ серію, но сама днёмъ серіи не становится.
      continue
    }
    текущая = 0
    началоТекущей = null
  }

  const мкСейчасъ = monthKey(now)
  const вЭтомъМѣсяцѣ = мѣсяцъ === мкСейчасъ ? заморозки : 0
  return {
    days: текущая,
    best: рекордъ,
    freezesUsed: вЭтомъМѣсяцѣ,
    freezesLeft: Math.max(0, FREEZES_PER_MONTH - вЭтомъМѣсяцѣ),
    todayDone: дни.has(now),
    restDay,
    since: началоТекущей,
  }
}
