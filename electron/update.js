const https = require('node:https')
const http = require('node:http')
const crypto = require('node:crypto')
const fs = require('node:fs')
const fsp = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const { spawn } = require('node:child_process')

/*
 * Обновление программы.
 *
 * Смысл: раздать приятелю установщик один раз, а дальше он сам берёт новые
 * версии. Устроено предельно просто — рядом с установщиками на вашем хостинге
 * лежит объявление update.json: версия, что нового, ссылки и контрольные
 * суммы. Программа его читает, сравнивает со своей версией и, если новее,
 * предлагает скачать.
 *
 * Почему без чужих библиотек. Обычный путь — electron-updater, но это чужой
 * код внутри вашей программы, английские сообщения и своя логика, которую
 * потом не переспоришь. Здесь всё на встроенных средствах Node: https,
 * crypto, fs. Ста строк хватает, и каждая на виду.
 *
 * Главное — подпись. Обновлятель по своей природе скачивает чужой файл и
 * запускает его с правами человѣка: это ровно тот механизм, который нужен
 * злоумышленнику. Контрольной суммы мало — она лежит в том же объявлении на
 * том же хостинге, и взломавший хостинг перепишет оба. Поэтому объявление
 * подписывается закрытым ключом, который лежит только у вас на машине, а в
 * программе зашит открытый. Подменённое объявление не пройдёт проверку, и
 * ничего не скачается и не запустится.
 *
 * Ключи заводятся один раз: npm run keygen. Выпуск версии: npm run release.
 */

// Открытый ключ и адрес хранятся отдельным файлом: его переписывает keygen,
// и он единственное место, которое надо трогать при переезде на другой хостинг.
const { ОТКРЫТЫЙ_КЛЮЧЪ, АДРЕСЪ_ПО_УМОЛЧАНІЮ } = require('./updatekey')

/** Больше этого объявление быть не может — защита от бесконечной выдачи. */
const ПРЕДѢЛЪ_ОБЪЯВЛЕНІЯ = 64 * 1024
/** И больше этого не может быть установщик. */
const ПРЕДѢЛЪ_ФАЙЛА = 500 * 1024 * 1024
const ТАЙМАУТЪ = 20_000

// ------------------------------------------------------------ сравненіе версій

/**
 * Версия новее нынешней.
 *
 * Сравниваются числа по частям, а не строки: иначе «1.10.0» оказалось бы
 * старше «1.9.0», потому что знак «1» меньше знака «9». Лишние части
 * считаются нулями, так что «1.1» и «1.1.0» — одно и то же.
 */
function новѣе(есть, пришла) {
  const ч = (s) => String(s || '').split('.').map((x) => parseInt(x, 10) || 0)
  const a = ч(есть)
  const b = ч(пришла)
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    const x = a[i] ?? 0
    const y = b[i] ?? 0
    if (y > x) return true
    if (y < x) return false
  }
  return false
}

// ------------------------------------------------------------ подпись

/**
 * Объявление подписано тем самым ключом.
 *
 * Проверяются именно те байты, что пришли по сети, а не разобранный и снова
 * собранный JSON: пересборка меняет порядок полей и пробелы, и подпись
 * перестала бы сходиться на ровном месте.
 */
function подписьВѣрна(байты, подпись64, ключ64 = ОТКРЫТЫЙ_КЛЮЧЪ) {
  if (!ключ64 || !подпись64) return false
  try {
    const ключ = crypto.createPublicKey({
      key: Buffer.from(ключ64, 'base64'),
      format: 'der',
      type: 'spki',
    })
    // Первый довод — null: у Ed25519 хеш встроен в саму подпись.
    return crypto.verify(null, байты, ключ, Buffer.from(подпись64, 'base64'))
  } catch {
    return false
  }
}

// ------------------------------------------------------------ разборъ объявленія

/** Какой файл нужен этой системе. */
const родъ = (platform = process.platform) => (platform === 'win32' ? 'win' : 'linux')

/**
 * Разбор объявления с проверкой всего, на что потом полагаемся.
 *
 * Проверяется здесь, а не по месту использования: объявление приходит из
 * сети, и половина полей в нём может отсутствовать или врать. Ошибка на этом
 * шаге честнее, чем скачивание в никуда.
 */
function разобрать(текстъ, платформа = process.platform) {
  let м
  try {
    м = JSON.parse(текстъ)
  } catch {
    throw new Error('объявление об обновлении испорчено')
  }
  if (!м || typeof м.version !== 'string') throw new Error('в объявлении нет версии')
  const ф = м.files?.[родъ(платформа)]
  if (!ф || typeof ф.url !== 'string') throw new Error('для этой системы обновления нет')
  if (!/^https:\/\//i.test(ф.url)) throw new Error('ссылка на обновление не по https')
  if (!/^[0-9a-f]{64}$/i.test(String(ф.sha256 || ''))) throw new Error('в объявлении нет контрольной суммы')
  const размѣръ = Number(ф.size) || 0
  if (размѣръ <= 0 || размѣръ > ПРЕДѢЛЪ_ФАЙЛА) throw new Error('в объявлении неправдоподобный размер файла')
  return {
    version: м.version,
    date: typeof м.date === 'string' ? м.date : '',
    notes: typeof м.notes === 'string' ? м.notes : '',
    url: ф.url,
    sha256: String(ф.sha256).toLowerCase(),
    size: размѣръ,
  }
}

// ------------------------------------------------------------ сѣть

/**
 * Скачивание с ограничением по объёму и по числу перенаправлений.
 *
 * Оба предела — не придирка: без них испорченный или враждебный ответ мог бы
 * гонять программу по кругу или наливать в память гигабайты.
 */
function достать(адресъ, пределъ, глубина = 0) {
  return new Promise((resolve, reject) => {
    if (глубина > 5) return reject(new Error('слишком много перенаправлений'))
    const модуль = адресъ.startsWith('http://') ? http : https
    const req = модуль.get(адресъ, { timeout: ТАЙМАУТЪ }, (res) => {
      if ([301, 302, 303, 307, 308].includes(res.statusCode) && res.headers.location) {
        res.resume()
        const слѣд = new URL(res.headers.location, адресъ).toString()
        return resolve(достать(слѣд, пределъ, глубина + 1))
      }
      if (res.statusCode !== 200) {
        res.resume()
        return reject(new Error(`сервер ответил ${res.statusCode}`))
      }
      const куски = []
      let всего = 0
      res.on('data', (c) => {
        всего += c.length
        if (всего > пределъ) {
          req.destroy()
          return reject(new Error('ответ больше допустимого'))
        }
        куски.push(c)
      })
      res.on('end', () => resolve(Buffer.concat(куски)))
      res.on('error', reject)
    })
    req.on('timeout', () => { req.destroy(); reject(new Error('сервер не отвечает')) })
    req.on('error', (e) => reject(new Error('сеть недоступна: ' + e.message)))
  })
}

/** Скачивание установщика на диск с отчётом о ходе. */
function скачатьВъФайлъ(адресъ, куда, ожидаемо, наХодъ, глубина = 0) {
  return new Promise((resolve, reject) => {
    if (глубина > 5) return reject(new Error('слишком много перенаправлений'))
    const модуль = адресъ.startsWith('http://') ? http : https
    const req = модуль.get(адресъ, { timeout: ТАЙМАУТЪ }, (res) => {
      if ([301, 302, 303, 307, 308].includes(res.statusCode) && res.headers.location) {
        res.resume()
        const слѣд = new URL(res.headers.location, адресъ).toString()
        return resolve(скачатьВъФайлъ(слѣд, куда, ожидаемо, наХодъ, глубина + 1))
      }
      if (res.statusCode !== 200) {
        res.resume()
        return reject(new Error(`сервер ответил ${res.statusCode}`))
      }
      const файлъ = fs.createWriteStream(куда)
      const хешъ = crypto.createHash('sha256')
      let всего = 0
      res.on('data', (c) => {
        всего += c.length
        if (всего > ожидаемо) {
          req.destroy()
          файлъ.destroy()
          return reject(new Error('файл больше объявленного'))
        }
        хешъ.update(c)
        if (наХодъ) наХодъ(всего, ожидаемо)
      })
      res.pipe(файлъ)
      файлъ.on('finish', () => файлъ.close(() => resolve({ размѣръ: всего, sha256: хешъ.digest('hex') })))
      файлъ.on('error', reject)
      res.on('error', reject)
    })
    req.on('timeout', () => { req.destroy(); reject(new Error('сервер не отвечает')) })
    req.on('error', (e) => reject(new Error('сеть недоступна: ' + e.message)))
  })
}

// ------------------------------------------------------------ проверка

const безъКосой = (s) => String(s || '').replace(/\/+$/, '')

/**
 * Есть ли новая версия.
 *
 * Возвращает описание находки или отказ с русской причиной. Ничего не
 * скачивает и не запускает: решение всегда за человѣкомъ.
 */
async function проверить({ адресъ, версія, платформа = process.platform } = {}) {
  const база = безъКосой(адресъ || АДРЕСЪ_ПО_УМОЛЧАНІЮ)
  if (/example\.invalid/.test(база)) {
    throw new Error('адрес обновлений не настроен: укажите его в electron/updatekey.js')
  }
  const [объявленіе, подпись] = await Promise.all([
    достать(`${база}/update.json`, ПРЕДѢЛЪ_ОБЪЯВЛЕНІЯ),
    достать(`${база}/update.json.sig`, ПРЕДѢЛЪ_ОБЪЯВЛЕНІЯ),
  ])
  if (!подписьВѣрна(объявленіе, подпись.toString('utf8').trim())) {
    throw new Error('подпись обновления не сошлась — файл подменён, ничего не скачано')
  }
  const м = разобрать(объявленіе.toString('utf8'), платформа)
  return { ...м, есть: новѣе(версія, м.version), текущая: версія }
}

// ------------------------------------------------------------ установка

/**
 * Скачать и поставить.
 *
 * Windows: запускается тот же установщик, что вы раздаёте, в тихом режиме, и
 * программа закрывается — иначе он не сможет заменить свои же файлы.
 *
 * Linux: новый AppImage кладётся рядом со старым и делается исполняемым.
 * Заменять на месте нельзя: работающий образ примонтирован из этого самого
 * файла, и перезапись на ходу роняет запущенную программу.
 */
async function поставить({ находка, наХодъ, каталогъ, запускать = true } = {}) {
  const врем = каталогъ || os.tmpdir()
  const имя = decodeURIComponent(new URL(находка.url).pathname.split('/').pop() || 'kashel-update')
  const куда = path.join(врем, имя)

  const итогъ = await скачатьВъФайлъ(находка.url, куда, находка.size, наХодъ)
  if (итогъ.размѣръ !== находка.size || итогъ.sha256 !== находка.sha256) {
    await fsp.rm(куда, { force: true })
    throw new Error('скачанный файл не совпал с объявленным — установка отменена')
  }

  if (process.platform === 'win32') {
    if (запускать) {
      // Отвязанный процесс переживёт закрытие программы: иначе установщик
      // умрёт вместе с ней, не успев ничего сделать.
      spawn(куда, ['/S'], { detached: true, stdio: 'ignore' }).unref()
    }
    return { путь: куда, действіе: 'установщик запущен, программа закроется' }
  }

  // Linux. Рядом с работающим образом, если программа запущена из AppImage.
  const текущій = process.env.APPIMAGE
  const рядомъ = текущій ? path.join(path.dirname(текущій), имя) : куда
  if (рядомъ !== куда) await fsp.copyFile(куда, рядомъ)
  await fsp.chmod(рядомъ, 0o755)
  return { путь: рядомъ, действіе: 'новая версия скачана рядом со старой — запустите её' }
}

module.exports = {
  новѣе, подписьВѣрна, разобрать, родъ, проверить, поставить,
  АДРЕСЪ_ПО_УМОЛЧАНІЮ, ПРЕДѢЛЪ_ОБЪЯВЛЕНІЯ, ПРЕДѢЛЪ_ФАЙЛА,
}
